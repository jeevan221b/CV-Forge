"""LaTeX toolchain detection and sandboxed compilation.

Only source generated by CV Forge's own template is compiled. Even so the compiler runs with
shell escape disabled, a fixed argv (no shell, no user-controlled arguments), a private build
directory, a minimal environment, a timeout and output size limits.
"""
from __future__ import annotations

import hashlib
import os
import re
import shutil
import subprocess
import tempfile
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Optional

MAX_TEX_BYTES = 1_000_000
MAX_PDF_BYTES = 25_000_000
JOB = "resume"
ENGINES = ("latexmk", "pdflatex", "xelatex", "lualatex", "tectonic")

INSTALL_HINTS = {
    "latex": {
        "macOS": "brew install tectonic   (small, downloads packages on first use)  or  brew install --cask mactex-no-gui",
        "Debian/Ubuntu": "sudo apt install texlive-latex-recommended texlive-latex-extra latexmk",
        "Termux": "pkg install texlive-installer && termux-install-tl   (or: pkg install tectonic)",
    },
    "pdftotext": {
        "macOS": "brew install poppler",
        "Debian/Ubuntu": "sudo apt install poppler-utils",
        "Termux": "pkg install poppler",
    },
}


@dataclass
class Toolchain:
    engine: Optional[str]
    engine_path: Optional[str]
    engine_version: str
    available_engines: list[str]
    pdftotext: bool
    can_compile: bool
    missing: list[dict] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class CompileResult:
    ok: bool
    engine: Optional[str]
    seconds: float
    tex_sha256: str
    pdf_path: Optional[Path] = None
    error: str = ""
    log_excerpt: str = ""


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _version(path: str) -> str:
    try:
        done = subprocess.run([path, "--version"], capture_output=True, timeout=15, check=False)
        return (done.stdout or done.stderr).decode("utf-8", "replace").strip().splitlines()[0][:120]
    except (OSError, subprocess.TimeoutExpired, IndexError):
        return ""


def detect_toolchain(preferred: Optional[str] = None) -> Toolchain:
    found = {name: shutil.which(name) for name in ENGINES}
    # latexmk is only a driver; it needs a real engine behind it.
    if found["latexmk"] and not found["pdflatex"]:
        found["latexmk"] = None
    available = [name for name in ENGINES if found[name]]
    engine = preferred if preferred in available else (available[0] if available else None)
    has_pdftotext = shutil.which("pdftotext") is not None
    missing, notes = [], []
    if not engine:
        missing.append({"name": "LaTeX compiler", "purpose": "Needed to turn the generated .tex into a PDF. "
                        "Without it you can still generate and download the .tex and compile it on Overleaf.",
                        "install": INSTALL_HINTS["latex"]})
    if not has_pdftotext:
        missing.append({"name": "pdftotext (Poppler)", "purpose": "Preferred PDF text extractor. The built-in "
                        "pypdf extractor is used instead, with less faithful layout.",
                        "install": INSTALL_HINTS["pdftotext"]})
    if engine == "tectonic":
        notes.append("Tectonic downloads the LaTeX packages it needs on first use, so the first compile needs "
                     "internet access and can take a minute. Later compiles work offline.")
    return Toolchain(engine=engine, engine_path=found.get(engine) if engine else None,
                     engine_version=_version(found[engine]) if engine else "", available_engines=available,
                     pdftotext=has_pdftotext, can_compile=engine is not None, missing=missing, notes=notes)


def _argv(engine: str, exe: str) -> list[list[str]]:
    """Fixed command lines. The only file name involved is the constant job name."""
    tex = f"{JOB}.tex"
    if engine == "tectonic":
        return [[exe, "--untrusted", "--keep-logs", "--outdir", ".", tex]]
    if engine == "latexmk":
        return [[exe, "-norc", "-pdf", "-interaction=nonstopmode", "-halt-on-error",
                 "-latexoption=-no-shell-escape", tex]]
    run = [exe, "-interaction=nonstopmode", "-halt-on-error", "-no-shell-escape", "-file-line-error", tex]
    return [run, run]  # second pass settles hyperref metadata


def _env() -> dict[str, str]:
    env = {k: os.environ[k] for k in ("PATH", "HOME", "LANG", "LC_ALL", "TMPDIR", "PREFIX", "XDG_CACHE_HOME",
                                      "TEXMFHOME", "TEXMFVAR", "SSL_CERT_FILE") if k in os.environ}
    env.update({"openin_any": "p", "openout_any": "p", "shell_escape": "f", "max_print_line": "200"})
    return env


def _excerpt(log: str) -> str:
    lines = log.splitlines()
    errors = [i for i, ln in enumerate(lines) if ln.startswith("!") or re.search(r":\d+: |^error:", ln)]
    if errors:
        first = errors[0]
        picked = lines[max(0, first - 2): first + 12]
    else:
        picked = lines[-25:]
    return "\n".join(ln[:300] for ln in picked)[:4000]


def compile_latex(source: str, out_dir: Path, *, timeout: int = 300, toolchain: Optional[Toolchain] = None) -> CompileResult:
    """Compile `source` and, only on success, place resume.pdf in out_dir.

    A stale PDF in out_dir is removed first so a failed build can never leave a PDF that does not
    correspond to the current source.
    """
    started = time.monotonic()
    digest = sha256_text(source)
    final_pdf = out_dir / f"{JOB}.pdf"
    final_pdf.unlink(missing_ok=True)
    tc = toolchain or detect_toolchain()

    def fail(error: str, log: str = "") -> CompileResult:
        return CompileResult(ok=False, engine=tc.engine, seconds=round(time.monotonic() - started, 1),
                             tex_sha256=digest, error=error, log_excerpt=_excerpt(log) if log else "")

    if not tc.can_compile or not tc.engine or not tc.engine_path:
        return fail("No LaTeX compiler is installed, so no PDF was produced. The .tex source is still available.")
    if len(source.encode("utf-8")) > MAX_TEX_BYTES:
        return fail("The generated source is unexpectedly large and was not compiled.")

    out_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="build-", dir=out_dir) as tmp:
        build = Path(tmp)
        (build / f"{JOB}.tex").write_text(source, encoding="utf-8")
        log = ""
        for argv in _argv(tc.engine, tc.engine_path):
            try:
                done = subprocess.run(argv, cwd=build, env=_env(), capture_output=True, timeout=timeout,
                                      check=False, stdin=subprocess.DEVNULL)
            except subprocess.TimeoutExpired:
                return fail(f"Compilation timed out after {timeout} seconds and was stopped."
                            + (" Tectonic may still be downloading packages; try again." if tc.engine == "tectonic" else ""))
            except OSError:
                return fail("The LaTeX compiler could not be started.")
            log_file = build / f"{JOB}.log"
            log = (log_file.read_text("utf-8", "replace") if log_file.exists() else "") \
                + "\n" + done.stdout.decode("utf-8", "replace") + "\n" + done.stderr.decode("utf-8", "replace")
            if done.returncode != 0:
                return fail(f"{tc.engine} reported an error (exit code {done.returncode}).", log)
        built = build / f"{JOB}.pdf"
        if not built.is_file():
            return fail("The compiler finished without producing a PDF.", log)
        size = built.stat().st_size
        if size == 0 or size > MAX_PDF_BYTES:
            return fail("The compiler produced an empty or oversized PDF.", log)
        with built.open("rb") as fh:
            if fh.read(5) != b"%PDF-":
                return fail("The compiler output is not a valid PDF.", log)
        shutil.move(str(built), final_pdf)
    return CompileResult(ok=True, engine=tc.engine, seconds=round(time.monotonic() - started, 1),
                         tex_sha256=digest, pdf_path=final_pdf)
